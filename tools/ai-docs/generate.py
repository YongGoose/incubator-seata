README_BODY = """
Reference material for AI coding assistants working on this repository.
Static analysis misses most of Seata's wiring: implementations are chosen at
runtime by name, RPC messages are dispatched by code, and modules are gated by
JDK version. These maps list those links so an assistant can look them up
instead of rediscovering them.

| File | Answers |
|---|---|
| [spi.md](spi.md) | Which implementations exist for an SPI interface, under which name, and where it is loaded |
| [rpc.md](rpc.md) | Which class a message type maps to, which processor receives it, and which method handles it |
| [modules.md](modules.md) | Which directory builds which artifact, what it depends on, and which JDK it needs |

The maps are generated from the code. If one looks wrong, fix the generator in
`tools/ai-docs/generate.py`, not the Markdown. CI runs `make ai-docs-check` and
fails when the maps are out of date; run `make ai-docs` to refresh them.
"""


def render_all():
    index = JavaIndex()
    return {
        "README.md": "%s\n# AI reference maps\n\n%s\n%s" % (LICENSE_HEADER, GENERATED_NOTE, README_BODY.lstrip()),
        "spi.md": build_spi(index),
        "rpc.md": build_rpc(index),
        "modules.md": build_modules(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/ai/ is out of date")
    args = parser.parse_args()

    rendered = render_all()
    if args.check:
        stale = []
        for name, content in sorted(rendered.items()):
            path = os.path.join(OUT_DIR, name)
            current = read(path) if os.path.exists(path) else ""
            if current != content:
                stale.append(name)
                diff = difflib.unified_diff(
                    current.splitlines(), content.splitlines(), "docs/ai/" + name, "generated", lineterm="", n=1)
                print("\n".join(list(diff)[:40]))
        if stale:
            print("\ndocs/ai/ is out of date: %s\nRun `make ai-docs` and commit the result." % ", ".join(stale))
            return 1
        print("docs/ai/ is up to date.")
        return 0

    os.makedirs(OUT_DIR, exist_ok=True)
    for name, content in rendered.items():
        with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8") as f:
            f.write(content)
    print("Wrote %d files to docs/ai/." % len(rendered))
    return 0


if __name__ == "__main__":
    sys.exit(main())
