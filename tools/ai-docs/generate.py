"""Generate the runtime wiring maps under docs/ai/.

Seata wires most of its extension points at runtime: SPI implementations are
picked by name through EnhancedServiceLoader, RPC messages are dispatched by
MessageType code, and modules are gated by JDK profiles. None of these links
show up in a static call graph, so this script extracts them from their
declarations and writes them as Markdown for AI coding assistants.

Usage:
    python3 tools/ai-docs/generate.py          # rewrite docs/ai/*.md
    python3 tools/ai-docs/generate.py --check  # fail if docs/ai/ is stale

Only the Python 3 standard library is used. Output is deterministic: no
timestamps and no line numbers, so it only changes when the wiring changes.
"""

