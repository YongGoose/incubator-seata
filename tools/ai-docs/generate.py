# RPC map
# --------------------------------------------------------------------------

REGISTER_RE = re.compile(r"registerProcessor\s*\(\s*MessageType\.(\w+)\s*,\s*(\w+)\s*,\s*([\w.()]+)\s*\)")
NEW_VAR_RE = r"\b%s\s*=\s*new\s+(\w+)\s*[(<]"
HANDLE_RE = re.compile(r"public\s+[\w<>]+\s+handle\s*\(\s*(\w+)\s+\w+[^)]*\)\s*\{")


def build_rpc(index):
    mt_path = index.by_fqn["org.apache.seata.core.protocol.MessageType"]
    codes = dict(re.findall(r"\bshort\s+(TYPE_\w+)\s*=\s*(-?\d+)\s*;", index.source(mt_path)))

    messages = defaultdict(list)
    for path in index.files:
        for m in re.finditer(r"return\s+MessageType\.(TYPE_\w+)\s*;", index.source(path)):
            messages[m.group(1)].append(path)

    registrations = defaultdict(list)
    for path in index.files:
        src = index.source(path)
        for m in REGISTER_RE.finditer(src):
            var_type = re.search(NEW_VAR_RE % re.escape(m.group(2)), src)
            processor = var_type.group(1) if var_type else m.group(2)
            executor = "IO thread" if m.group(3) == "null" else m.group(3)
            registrations[m.group(1)].append((os.path.basename(path)[:-5], processor, executor, path))

    rows = []
    for name, value in sorted(codes.items(), key=lambda kv: (int(kv[1]), kv[0])):
        msg = ", ".join(code(os.path.basename(p)[:-5]) for p in sorted(messages.get(name, [])) if "/io/seata/" not in p)
        regs = "<br>".join(
            "%s → %s" % (owner, code(proc)) for owner, proc, _, _ in sorted(registrations.get(name, []))
        )
        rows.append((value, code(name), msg or "-", regs or "-"))
    message_table = table(["Code", "MessageType", "Message class", "Received by (remoting → processor)"], rows)

    owners = defaultdict(list)
    for name, regs in registrations.items():
        for owner, proc, executor, path in regs:
            owners[(owner, path)].append((name, proc, executor))
    owner_sections = []
    for (owner, path), regs in sorted(owners.items()):
        owner_sections.append("### %s\n\nRegistered in %s.\n\n%s" % (
            code(owner), code(path),
            table(["MessageType", "Processor", "Executor"],
                  [(code(n), code(p), e) for n, p, e in sorted(regs, key=lambda r: int(codes.get(r[0], 0)))]),
        ))

    dispatch_rows = []
    for path in index.files:
        src = index.source(path)
        handler = os.path.basename(path)[:-5]
        for m in HANDLE_RE.finditer(src):
            do_call = re.search(r"\b(do[A-Z]\w*)\s*\(", method_body(src, m.end()))
            if not do_call or not m.group(1).endswith("Request"):
                continue
            impls = sorted(
                os.path.basename(p)[:-5]
                for p in index.files
                if p != path
                and handler in index.superclasses(p)
                and re.search(r"(protected|public)\s+void\s+%s\s*\(" % do_call.group(1), index.source(p))
            )
            dispatch_rows.append((
                code(m.group(1)),
                code("%s#handle" % handler),
                code(do_call.group(1)),
                ", ".join(code(c) for c in impls) or "%s (no override)" % code(handler),
            ))
    dispatch_rows.sort()

    others = []
    for path in index.files:
        for m in re.finditer(r"\w+\.registerProcessor\s*\(\s*new\s+(\w+)\s*\(", index.source(path)):
            others.append((code(m.group(1)), code(path)))

    intro = """
How a Seata RPC message travels. Netty remoting classes register one processor
per `MessageType` code in a dispatch table (`AbstractNettyRemoting#processorTable`),
so a processor is never called directly and has no callers in a static call graph.
`IO thread` means the processor runs on the Netty I/O thread (no executor).
"""
    body = "## Message types\n\n" + message_table
    body += "\n\n## Processors by remoting endpoint\n\n" + "\n\n".join(owner_sections)
    body += "\n\n## Request handling\n\nTransaction requests reach their handler through `request.handle(handler)`, " \
            "which picks the `handle` overload by request type and then calls a `do*` method.\n\n"
    body += table(["Request", "Entry point", "Calls", "Implemented in"], dispatch_rows)
    if others:
        body += "\n\n## Other processors\n\nRegistered on non-Netty RPC servers (for example the Raft RPC server).\n\n"
        body += table(["Processor", "Registered in"], sorted(set(others)))
    return document("RPC map", intro, body)


