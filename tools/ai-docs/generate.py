def strip_ns(elem):
    for e in elem.iter():
        if isinstance(e.tag, str) and "}" in e.tag:
            e.tag = e.tag.split("}", 1)[1]
    return elem


def text(elem, tag):
    child = elem.find(tag)
    return child.text.strip() if child is not None and child.text else ""


def build_modules():
    poms = {}
    for pom in git_ls_files("pom.xml", "*/pom.xml"):
        try:
            root = strip_ns(ET.parse(os.path.join(ROOT, pom)).getroot())
        except ET.ParseError:
            continue
        poms[os.path.dirname(pom) or "."] = root

    artifact_of = {d: text(r, "artifactId") for d, r in poms.items()}
    known = set(artifact_of.values())

    root_pom = poms["."]
    default_modules = [m.text.strip() for m in root_pom.findall("modules/module")]
    gated = []
    for profile in root_pom.findall("profiles/profile"):
        jdk = text(profile, "activation/jdk")
        mods = [m.text.strip() for m in profile.findall("modules/module")]
        if jdk and mods:
            gated.append((jdk, text(profile, "id"), mods))

    rows = []
    for d in sorted(poms):
        if d == ".":
            continue
        r = poms[d]
        deps = []
        for dep in r.findall("dependencies/dependency"):
            aid = text(dep, "artifactId")
            if aid in known and aid != artifact_of[d]:
                scope = text(dep, "scope")
                deps.append(aid + (" (%s)" % scope if scope and scope != "compile" else ""))
        rows.append((code(d), code(artifact_of[d]), text(r, "packaging") or "jar", ", ".join(sorted(deps)) or "-"))

    gate_rows = [(code(jdk), code(pid), ", ".join(code(m) for m in mods)) for jdk, pid, mods in gated]
    intro = """
Maven modules of this repository and how they depend on each other. Use the
directory with `./mvnw -pl <dir> -am` to build one module with its dependencies.
Some modules are only part of the reactor on newer JDKs, so a build on an older
JDK silently skips them.
"""
    body = "## JDK-gated modules\n\nDeclared as JDK-activated profiles in the root `pom.xml`. " \
           "The default build lists %d modules.\n\n" % len(default_modules)
    body += table(["Activated on JDK", "Profile", "Adds modules"], gate_rows)
    body += "\n\n## Modules\n\nOnly dependencies on other modules of this repository are listed.\n\n"
    body += table(["Directory", "ArtifactId", "Packaging", "Depends on"], rows)
    return document("Module map", intro, body)


