# Source index
# --------------------------------------------------------------------------


def git_ls_files(*patterns):
    out = subprocess.check_output(["git", "ls-files", "--", *patterns], cwd=ROOT, text=True)
    return sorted(line for line in out.splitlines() if line)


def is_main(path):
    return "/src/test/" not in path and not path.startswith("test-suite/")


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8", errors="replace") as f:
        return f.read()


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


class JavaIndex:
    """Maps class names to source files for main (non-test) Java code."""

    def __init__(self):
        self.files = [p for p in git_ls_files("*.java") if is_main(p)]
        self.by_fqn = {}
        self.by_simple = defaultdict(list)
        self._src = {}
        for path in self.files:
            name = os.path.basename(path)[:-5]
            m = re.search(r"^\s*package\s+([\w.]+)\s*;", self.source(path), re.M)
            fqn = "%s.%s" % (m.group(1), name) if m else name
            self.by_fqn[fqn] = path
            self.by_simple[name].append(path)

    def source(self, path):
        if path not in self._src:
            self._src[path] = strip_comments(read(path))
        return self._src[path]

    def package_of(self, path):
        m = re.search(r"^\s*package\s+([\w.]+)\s*;", self.source(path), re.M)
        return m.group(1) if m else ""

    def resolve(self, simple, context_path):
        """Resolve a simple class name as seen from context_path to an FQN."""
        src = self.source(context_path)
        m = re.search(r"^\s*import\s+([\w.]+\.%s)\s*;" % re.escape(simple), src, re.M)
        if m:
            return m.group(1)
        same_pkg = "%s.%s" % (self.package_of(context_path), simple)
        if same_pkg in self.by_fqn:
            return same_pkg
        candidates = self.by_simple.get(simple, [])
        if len(candidates) == 1:
            return self.fqn_of(candidates[0])
        return None

    def superclasses(self, path):
        """Simple names of the classes `path` extends, nearest first."""
        chain = []
        current = path
        while current and len(chain) < 10:
            name = os.path.basename(current)[:-5]
            m = re.search(r"\bclass\s+%s\b[^{]*?\bextends\s+(\w+)" % re.escape(name), self.source(current))
            if not m:
                break
            chain.append(m.group(1))
            fqn = self.resolve(m.group(1), current)
            current = self.by_fqn.get(fqn) if fqn else None
        return chain

    def fqn_of(self, path):
        pkg = self.package_of(path)
        name = os.path.basename(path)[:-5]
        return "%s.%s" % (pkg, name) if pkg else name

    def resolve_constant(self, expr, context_path):
        """Turn `"db"` or `JdbcConstants.MYSQL` into its string value when possible."""
        expr = expr.strip()
        m = re.fullmatch(r'"([^"]*)"', expr)
        if m:
            return m.group(1)
        m = re.fullmatch(r"(\w+)\.(\w+)", expr)
        if m:
            fqn = self.resolve(m.group(1), context_path)
            path = self.by_fqn.get(fqn) if fqn else None
            if path:
                c = re.search(r'\b%s\s*=\s*"([^"]*)"' % re.escape(m.group(2)), self.source(path))
                if c:
                    return c.group(1)
        return None


def method_body(src, start):
    """Text from just after an opening brace at `start - 1` to its matching close brace."""
    depth = 1
    i = start
    while i < len(src) and depth:
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
        i += 1
    return src[start:i]


def module_of(path):
    """Nearest directory above `path` that has a pom.xml."""
    d = os.path.dirname(path)
    while d:
        if os.path.exists(os.path.join(ROOT, d, "pom.xml")):
            return d
        d = os.path.dirname(d)
    return "."


def code(text):
    return "`%s`" % text


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |")
    return "\n".join(lines)


def document(title, intro, body):
    return "%s\n# %s\n\n%s\n%s\n\n%s\n" % (LICENSE_HEADER, title, GENERATED_NOTE, intro.strip(), body.strip())


